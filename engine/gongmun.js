// 공문 표지: 수신·제목·(경유)·붙임·끝.·시행/접수·결재 칸. 둘 이상이면 공문
const GONGMUN_MARKS = [
  /^[ \t|]*수신(?=[\s|:]|$)/m,
  /^[ \t|]*제목(?=[\s|:]|$)/m,
  /^[ \t]*\(경유\)/m,
  /^[ \t|]*붙임(?=[\s\d|:]|$)/m,
  /[^\s]\s끝\.\s*$/m,
  /^[ \t]*(?:시행|접수)\s.*(?:19|20)\d{2}\./m,
  /(?:기안자|결재권자|협조자)(?=[\s|]|$)/m,
];
// 개조식 보고서: □·○·❍ 로 시작하는 줄이 셋 이상
const REPORT_BULLETS = /^[ \t*>]*(?:\*\*)?[□■○❍◦◯]/gm;

function isGongmun(text) {
  if (typeof text !== 'string') return false;
  if (GONGMUN_MARKS.filter((re) => re.test(text)).length >= 2) return true;
  return (text.match(REPORT_BULLETS) || []).length >= 3;
}

